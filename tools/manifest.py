#!/usr/bin/env python3
"""Generate and verify the SHA-256 manifests for the pack.

The pack records, for every vanilla file it replaces, what it replaced and why,
so that every change is traceable. Two manifests carry the hashes:

    MANIFEST/vanilla-hashes.json  - the vanilla 26.3 sources the pack was
                                    written against, with size, line count and
                                    SHA-256.
    MANIFEST/modified-files.json  - per replaced file: the vanilla source, the
                                    pack file, both SHA-256 values and the
                                    reason for the change.

The hash fields are generated by this script rather than written by hand,
because a hand-copied hash is worse than no hash: it looks verified and is not.

    python3 tools/manifest.py --write     fill in every hash field
    python3 tools/manifest.py --check     verify them, exit 1 on a mismatch

The "reason" text in modified-files.json is hand-written and is never touched
by this script.
"""

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Every replaced file, with the vanilla source it derives from.
