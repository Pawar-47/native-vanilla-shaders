GENERATED = ("MANIFEST/vanilla-hashes.json", "MANIFEST/modified-files.json")


def digest(path):
    hasher = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def find_vanilla():
    # The supplied archive is extracted under reference/vanilla-stock/ and
    # intentionally retains its source directory's trailing space.
    for parent in (os.path.join(ROOT, "reference", "vanilla-stock"), ROOT):
        if not os.path.isdir(parent):
            continue
        for name in sorted(os.listdir(parent)):
            if name.strip().lower() == "vanilla-stock" and os.path.isdir(os.path.join(parent, name)):
                return os.path.join(parent, name)
    return None


def vanilla_index(vanilla):
    result = {}
    if not vanilla:
        return result
    for base, _dirs, names in os.walk(vanilla):
        for name in names:
            path = os.path.join(base, name)
            rel = os.path.relpath(path, vanilla).replace(os.sep, "/")
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                text = handle.read()
            result[rel] = {
                "path": "Vanilla-stock /" + rel,
                "bytes": os.path.getsize(path),
                "lines": len(text.splitlines()),
                "sha256": digest(path),
            }
    return result


def build(vanilla):
    sources = vanilla_index(vanilla)
    hashes = {
        "generated_by": "tools/manifest.py --write",
        "minecraft_version": "26.3",
        "note": "SHA-256 of every vanilla 26.3 shader source the pack was written against. "
                "Regenerate after updating the vanilla reference folder.",
        "files": sources,
    }

    replaced = []
    for pack_rel, vanilla_rel, reason in REPLACED:
        pack_path = os.path.join(ROOT, pack_rel)
        entry = {
            "pack_file": pack_rel,
            "vanilla_source": "Vanilla-stock /" + vanilla_rel,
            "reason": reason,
            "pack_sha256": digest(pack_path) if os.path.isfile(pack_path) else None,
            "vanilla_sha256": sources.get(vanilla_rel, {}).get("sha256"),
        }
        replaced.append(entry)

    added = []
    for pack_rel, reason in POST_FILES:
        pack_path = os.path.join(ROOT, pack_rel)
        added.append({
            "pack_file": pack_rel,
            "vanilla_source": None,
            "reason": reason,
            "pack_sha256": digest(pack_path) if os.path.isfile(pack_path) else None,
        })

    modified = {
        "generated_by": "tools/manifest.py --write",
        "minecraft_version": "26.3",
        "note": "One entry per file the pack places at a path vanilla also uses, plus the "
                "files the pack adds. Regenerate the hashes; the reasons are hand-written.",
        "replaced": replaced,
        "added": added,
    }
    return hashes, modified


def main(argv):
    mode = argv[1] if len(argv) > 1 else "--help"
    vanilla = find_vanilla()
    if vanilla is None:
        print("error: no extracted Vanilla-stock directory found under reference/vanilla-stock or next to the pack")
        return 2

    hashes, modified = build(vanilla)

    if mode == "--write":
        for rel, payload in zip(GENERATED, (hashes, modified)):
            path = os.path.join(ROOT, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, indent=2)
                handle.write("\n")
            print("wrote %s" % rel)
        return 0

    if mode == "--check":
        problems = 0
        for rel, payload in zip(GENERATED, (hashes, modified)):
            path = os.path.join(ROOT, rel)
            if not os.path.isfile(path):
                print("missing %s - run --write" % rel)
                problems += 1
                continue
            try:
                recorded = json.loads(open(path, encoding="utf-8").read())
            except ValueError as error:
                print("%s is not valid JSON: %s" % (rel, error))
                problems += 1
                continue
            fresh = json.dumps(payload, indent=2)
            if json.dumps(recorded, indent=2) != fresh:
                print("%s is out of date - run --write" % rel)
                problems += 1
        if problems:
            return 1
        print("PASS: manifests match the pack and the vanilla reference")
        return 0

    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
